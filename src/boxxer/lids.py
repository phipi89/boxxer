"""Generate a matching uncompensated telescoping lid from one tray."""
import xml.etree.ElementTree as ET

from svgpathtools.path import transform as transform_path


def matching_lid(graph, lid_height=None):
    from .panelgraph import PanelGraph, translation_2d
    model = graph._resize_structure()
    if model.get("status") != "supported" or model.get("kind") != "single":
        raise ValueError("--with-lid requires one recognizable rectangular tray without an existing lid")
    walls = graph._adjacency()[model["principal"]]
    if len(walls) != 4:
        raise ValueError("A matching telescoping lid requires a tray with four structural walls")
    ids = {panel.id for panel in graph.panels}
    ids.update(shape.id for panel in graph.panels for shape in panel.internal)
    prefix = "lid-"
    while any(prefix+identifier in ids for identifier in ids):
        prefix = "copy-"+prefix
    paths = [panel.path for panel in graph.panels]
    x0, y0 = min(path.bbox()[0] for path in paths), min(path.bbox()[2] for path in paths)
    y1 = max(path.bbox()[3] for path in paths)
    lid_shift = complex(10-x0, 10-y0)
    base_shift = lid_shift+complex(0, y1-y0+10)
    records = []
    for shift, name_prefix in ((lid_shift, prefix), (base_shift, "")):
        for panel in graph.panels:
            records.append((len(records), name_prefix+panel.id,
                            transform_path(panel.path, translation_2d(shift)), panel.outside_hint,
                            "auto", panel.corner_treatments))
            for shape in panel.internal:
                records.append((len(records), name_prefix+shape.id,
                                transform_path(shape.path, translation_2d(shift)), shape.outside_hint,
                                shape.feature, shape.corner_treatments))
    # Effects are regenerated by _source_document. Replicate each explicit guide
    # for both copies; inherited source symmetry has already been expanded once.
    root = graph._source_document(records, include_guides=False)
    from .panelgraph import SVG
    from svgpathtools import Line, Path
    identifiers = {node.get("id") for node in root.iter()}
    for shift, name_prefix in ((lid_shift, prefix), (base_shift, "")):
        for seam in graph.seams:
            if not seam.annotated:
                continue
            path = Path(Line(seam.start+shift, seam.end+shift))
            if abs(seam.angle) == 180:
                path.append(Line(path.end, path.start))
            attributes = {"id": name_prefix+"boxxer-guide-"+seam.id, "d": path.d(), "fill": "none", "stroke": "#ff0000"}
            while attributes["id"] in identifiers:
                attributes["id"] += "-copy"
            identifiers.add(attributes["id"])
            if seam.angle < 0:
                attributes["stroke-dasharray"] = "1,1"
            ET.SubElement(root, f"{{{SVG}}}path", attributes)
    result = PanelGraph(graph.source_name, graph.near, graph.snap_near,
                        _source_bytes=ET.tostring(root, encoding="utf-8", xml_declaration=True),
                        _source_name=graph.source_name)
    if result.structure.get("status") != "inferred" or result.structure.get("layout") != "separate":
        raise ValueError("Generated tray and lid cannot be recognized as two independent box shells")
    result.preset_defaults = dict(graph.preset_defaults)
    result.finger_cutout_settings = dict(graph.finger_cutout_settings)
    result.generated_lid = {"base": model["principal"], "lid": prefix+model["principal"],
                            "method": "same-design-telescoping", "source_gap": 10.0}
    if lid_height is not None:
        result = result.resized(lid_height=lid_height)
    return result
